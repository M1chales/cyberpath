export const TOTAL_WEEKS = CURRICULUM.reduce((sum, phase) => sum + phase.modules.length, 0)

export function allModules() {
  return CURRICULUM.flatMap((phase) => phase.modules.map((m) => ({ ...m, phaseId: phase.id, phaseTitle: phase.title, phaseColor: phase.color })))
}

export function findModule(id: string) {
  return allModules().find((m) => m.id === id)
}
